import { readFile, writeFile } from 'node:fs/promises';

const source = new URL('../docs/concepts/spatial-player/index.html', import.meta.url);
const output = new URL('../docs/concepts/spatial-player/embed.js', import.meta.url);
const html = (await readFile(source, 'utf8')).replace(/\r\n/g, '\n');

if (/<script\b[^>]*\bsrc\s*=\s*["'][^"']*\bembed\.js\b/i.test(html)) {
  throw new Error('The player source must not load its generated embed.js.');
}
if (!/<html\b/i.test(html)) throw new Error('Missing player HTML root.');

// about:srcdoc inherits the parent origin, preserving its playback permission.
// The parent inserts a base URL in <head> so assets still resolve beside index.html.
const document = html.replace(/<html\b/, '<html data-bili-embedded="1"');
const serialized = JSON.stringify(document)
  .replace(/</g, '\\u003c')
  .replace(/\u2028/g, '\\u2028')
  .replace(/\u2029/g, '\\u2029');
const generated = '// Generated by scripts/build-concept-embed.mjs. Do not edit by hand.\n'
  + '// Source: docs/concepts/spatial-player/index.html\n'
  + `window.biliPlayerDocument = ${serialized};\n`;

if (process.argv.includes('--check')) {
  const existing = await readFile(output, 'utf8').catch(error => {
    if (error.code === 'ENOENT') return '';
    throw error;
  });
  if (existing.replace(/\r\n/g, '\n') !== generated) {
    throw new Error('Player embed is stale. Run node scripts/build-concept-embed.mjs.');
  }
  console.log('Player embed matches index.html.');
} else {
  await writeFile(output, generated, 'utf8');
  console.log('Generated docs/concepts/spatial-player/embed.js.');
}
